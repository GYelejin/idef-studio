"""
Матрица Фибоначчи
Сгенерировано автоматически в едином диалоговом контексте.
Стиль: чистые функции, внутренние импорты.
"""

from __future__ import annotations

# ==============================================================================
# Функции
# ==============================================================================

# [A1] Создание матрицы заданного размера
def создание_матрицы_заданного_размера_a1(размер):
    from typing import List
    return [[0 for _ in range(размер)] for _ in range(размер)]

# [A2] Генерация чисел Фибоначчи в необходимом количестве
def генерация_чисел_фибоначчи_в_необходимом_количестве_a2(размер, логика_генерации):
    from typing import List
    количество = размер * размер
    последовательность = []
    а, б = логика_генерации
    for _ in range(количество):
        последовательность.append(а)
        а, б = б, а + б
    return последовательность

# [A31] Получение позиции числа Фибоначи
def получение_позиции_числа_фибоначи_a31(последовательность_чисел_фибоначчи, сигнал_о_занятости_позиции, запрос_следующего_числа, генератор_случайных_чисел):
    import random
    размер = int(len(последовательность_чисел_фибоначчи)**0.5)
    строка = random.randint(0, размер - 1)
    столбец = random.randint(0, размер - 1)
    return (строка, столбец)

# [A32] Проверка занята ли позиция другим
def проверка_занята_ли_позиция_другим_a32(пустая_матрица, сгенерированная_позиция):
    from typing import Tuple
    строка, столбец = сгенерированная_позиция
    занято = пустая_матрица[строка][столбец] != 0
    return (пустая_матрица, сгенерированная_позиция), занято

# [A33] Поставить число на место
def поставить_число_на_место_a33(получение_числа_и_позиции, число_фибоначчи):
    from typing import Tuple
    матрица, позиция = получение_числа_и_позиции
    строка, столбец = позиция
    матрица[строка][столбец] = число_фибоначчи
    return True, матрица

# [A3] Заполнение Матрицы числами Фибоначчи в случайном порядке
def заполнение_матрицы_числами_фибоначчи_в_случайном_порядке_a3(пустая_матрица, последовательность_чисел_фибоначчи, генератор_случайных_чисел):
    from typing import List
    матрица = [строка[:] for строка in пустая_матрица]
    for число in последовательность_чисел_фибоначчи:
        поставлено = False
        while not поставлено:
            позиция = получение_позиции_числа_фибоначи_a31(последовательность_чисел_фибоначчи, False, False, генератор_случайных_чисел)
            данные, занято = проверка_занята_ли_позиция_другим_a32(матрица, позиция)
            if not занято:
                сигнал, матрица = поставить_число_на_место_a33(данные, число)
                поставлено = True
    return матрица

# [A0] Заполнение случайным образом матрицы последовательными без повторений числами Фибоначчи
def заполнение_случайным_образом_матрицы_последовательными_без_повторений_числами_фибоначчи_a0(размер, логика_генерации, генератор_случайных_чисел):
    from typing import List
    пустая_матрица = создание_матрицы_заданного_размера_a1(размер)
    последовательность = генерация_чисел_фибоначчи_в_необходимом_количестве_a2(размер, логика_генерации)
    результат = заполнение_матрицы_числами_фибоначчи_в_случайном_порядке_a3(пустая_матрица, последовательность, генератор_случайных_чисел)
    return результат

# ==============================================================================
# Точка входа и ввод данных
# ==============================================================================

def main() -> None:
    import random
    print("=== Запуск: Матрица Фибоначчи ===")

    # Подготовка входных данных конвейера:
    размер = int(input("Введите размерность матрицы (N x N) [Enter: 3]: ") or "3")
    логика_генерации = (0, 1)  # Базовая логика генерации (начальные члены F0=0, F1=1)
    генератор_случайных_чисел = random.Random(int(input("Введите seed генератора случайных чисел [Enter: 42]: ") or "42"))

    try:
        результат = заполнение_случайным_образом_матрицы_последовательными_без_повторений_числами_фибоначчи_a0(размер=размер, логика_генерации=логика_генерации, генератор_случайных_чисел=генератор_случайных_чисел)
        print("Выполнение завершено успешно:")
        if isinstance(результат, list):
            for строка in результат:
                print(" ", строка)
        else:
            print(результат)
    except Exception as e:
        print(f"Ошибка при выполнении конвейера: {e}")


if __name__ == "__main__":
    main()
