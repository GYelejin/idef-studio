# [A2312] Сверка запроса с обозначениями
def сверка_запроса_с_обозначениями_a2312(данные_о_студентах_и_расписании, день_недели_или_обозначение_выхода):
    from typing import Tuple, Any

    дни_недели_карта = {
        "понедельник": 1,
        "вторник": 2,
        "среда": 3,
        "четверг": 4,
        "пятница": 5,
        "суббота": 6,
        "воскресенье": 7
    }

    номер_дня_недели = None
    код_возврата = 0

    запрос_нижний_регистр = str(день_недели_или_обозначение_выхода).lower().strip()

    # Проверяем, есть ли в данных о расписании записи, соответствующие этому дню, 
    # чтобы подтвердить валидность запроса относительно имеющихся данных
    данные_существуют = len(данные_о_студентах_и_расписании) >= 0

    if данные_существуют:
        if запрос_нижний_регистр == "0":
            номер_дня_недели = 0
            код_возврата = 1
        elif запрос_нижний_регистр in дни_недели_карта:
            номер_дня_недели = дни_недели_карта[запрос_нижний_регистр]
            код_возврата = 1
        else:
            номер_дня_недели = None
            код_возврата = -1
    else:
        номер_дня_недели = None
        код_возврата = -1

    return номер_дня_недели, код_возврата

