# [A11] Прочитать таблицу из файла
def прочитать_таблицу_из_файла_a11(путь_к_файлу, ресурсы=None, библиотеки=None):
    import pandas as pd
    import os

    _ = (ресурсы, библиотеки)
    расширение = os.path.splitext(путь_к_файлу)[1].lower()
    
    if расширение == '.csv':
        данные = pd.read_csv(путь_к_файлу)
    elif расширение in ['.xls', '.xlsx']:
        данные = pd.read_excel(путь_к_файлу)
    else:
        raise ValueError("Неподдерживаемый формат файла. Используйте CSV или Excel.")
        
    return данные

# [A12] Подготовить столбцы с датами к обработке
def подготовить_столбцы_с_датами_к_обработке_a12(таблица_с_данными, ресурсы=None, библиотеки=None):
    import pandas as pd
    
    _ = (ресурсы, библиотеки)
    результат = таблица_с_данными.copy()
    
    for столбец in результат.columns:
        if pd.api.types.is_datetime64_any_dtype(результат[столбец]) or \
           (результат[столбец].dtype == 'object' and 'date' in столбец.lower()):
            результат[столбец] = pd.to_datetime(результат[столбец], errors='coerce')
            
    return результат

# [A13] Разделить данные на обучающую и тестовую выборки
def разделить_данные_на_обучающую_и_тестовую_выборки_a13(подготовленная_таблица_с_данными, ресурсы=None, библиотеки=None):
    from sklearn.model_selection import train_test_split
    
    _ = (ресурсы, библиотеки)
    тестовая_выборка, обучающая_выборка = train_test_split(подготовленная_таблица_с_данными, test_size=0.2, random_state=42)
    
    return тестовая_выборка, обучающая_выборка

# [A14] Заполнить отсутствующие данные медианой/спец. пометкой
def заполнить_отсутствующие_данные_медианой_спец_пометкой_a14(сырая_тестовая_выборка, сырая_обучающая_выборка, ресурсы=None, библиотеки=None):
    import pandas as pd
    
    _ = (ресурсы, библиотеки)
    обучающая_копия = сырая_обучающая_выборка.copy()
    тестовая_копия = сырая_тестовая_выборка.copy()
    
    for столбец in обучающая_копия.columns:
        if pd.api.types.is_numeric_dtype(обучающая_копия[столбец]):
            медиана = обучающая_копия[столбец].median()
            обучающая_копия[столбец] = обучающая_копия[столбец].fillna(медиана)
            тестовая_копия[столбец] = тестовая_копия[столбец].fillna(медиана)
        else:
            пометка = "Неизвестно"
            обучающая_копия[столбец] = обучающая_копия[столбец].fillna(пометка)
            тестовая_копия[столбец] = тестовая_копия[столбец].fillna(пометка)
            
    return обучающая_копия, тестовая_копия

# [A15] Масштабирование числовых признаков
def масштабирование_числовых_признаков_a15(дополненная_обучающая_выборка, дополненная_тестовая_выборка, ресурсы=None, библиотеки=None):
    import pandas as pd
    from sklearn.preprocessing import StandardScaler
    
    _ = (ресурсы, библиотеки)
    обучающая_копия = дополненная_обучающая_выборка.copy()
    тестовая_копия = дополненная_тестовая_выборка.copy()
    
    числовые_столбцы = обучающая_копия.select_dtypes(include=['number']).columns
    
    if len(числовые_столбцы) > 0:
        скалер = StandardScaler()
        обучающая_копия[числовые_столбцы] = скалер.fit_transform(обучающая_копия[числовые_столбцы])
        тестовая_копия[числовые_столбцы] = скалер.transform(тестовая_копия[числовые_столбцы])
        
    return обучающая_копия, тестовая_копия

# [A16] Применить OHE в случае необходимости
def применить_в_случае_необходимости_a16(подготовленная_обучающая_выборка, подготовленная_тестовая_выборка, ресурсы=None, библиотеки=None):
    import pandas as pd
    
    _ = (ресурсы, библиотеки)
    обучающая_копия = подготовленная_обучающая_выборка.copy()
    тестовая_копия = подготовленная_тестовая_выборка.copy()
    
    категориальные_столбцы = обучающая_копия.select_dtypes(include=['object', 'category']).columns
    
    if len(категориальные_столбцы) > 0:
        обучающая_копия = pd.get_dummies(обучающая_копия, columns=категориальные_столбцы)
        тестовая_копия = pd.get_dummies(тестовая_копия, columns=категориальные_столбцы)
        
        все_столбцы = обучающая_копия.columns
        for столбец in все_столбцы:
            if столбец not in тестовая_копия.columns:
                тестовая_копия[столбец] = 0
        
        тестовая_копия = тестовая_копия[все_столбцы]
        
    return обучающая_копия, тестовая_копия

# [A1] Предобработка данных
def предобработка_данных_a1(путь_к_файлу, библиотеки=None, ресурсы=None):
    import pandas as pd

    данные = прочитать_таблицу_из_файла_a11(путь_к_файлу, ресурсы, библиотеки)
    данные_с_датами = подготовить_столбцы_с_датами_к_обработке_a12(данные, ресурсы, библиотеки)
    тест_сырой, обуч_сырой = разделить_данные_на_обучающую_и_тестовую_выборки_a13(данные_с_датами, ресурсы, библиотеки)
    обуч_заполненная, тест_заполненная = заполнить_отсутствующие_данные_медианой_спец_пометкой_a14(тест_сырой, обуч_сырой, ресурсы, библиотеки)
    обуч_масштаб, тест_масштаб = масштабирование_числовых_признаков_a15(обуч_заполненная, тест_заполненная, ресурсы, библиотеки)
    обуч_финал, тест_финал = применить_в_случае_необходимости_a16(обуч_масштаб, тест_масштаб, ресурсы, библиотеки)
    
    return обуч_финал, тест_финал

# [A2] Обучение/использование модели для предсказания производственных данных
def обучение_использование_модели_для_предсказания_производственных_данных_a2(обучающая_выборка, тестовая_выборка, обученная_модель=None, нейросетевые_модели=None, библиотеки=None, ресурсы=None):
    from sklearn.ensemble import RandomForestRegressor
    from sklearn.metrics import mean_absolute_error, r2_score
    
    _ = (нейросетевые_модели, библиотеки, ресурсы)
    
    if обучающая_выборка.empty or тестовая_выборка.empty:
        raise ValueError("Выборки не должны быть пустыми")

    целевой_столбец = обучающая_выборка.columns[-1]
    
    x_обучение = обучающая_выборка.drop(columns=[целевой_столбец])
    y_обучение = обучающая_выборка[целевой_столбец]
    x_тест = тестовая_выборка.drop(columns=[целевой_столбец])
    y_тест = тестовая_выборка[целевой_столбец]
    
    if обученная_модель is None:
        модель = RandomForestRegressor(n_estimators=100, random_state=42)
        модель.fit(x_обучение, y_обучение)
    else:
        модель = обученная_модель
        
    предсказания = модель.predict(x_тест)
    
    mae = mean_absolute_error(y_тест, предсказания)
    r2 = r2_score(y_тест, предсказания)
    
    метрики = {"MAE": mae, "R2": r2}
    
    return метрики, модель

# [A3] Создание графиков с результатами
def создание_графиков_с_результатами_a3(обученная_модель, библиотеки=None, ресурсы=None):
    import matplotlib.pyplot as plt
    import pandas as pd
    import numpy as np

    настройки_визуализации = "стандартные" if библиотеки is None else "кастомные"
    размер_буфера = 1024 if ресурсы is None else ресурсы
    
    график_важности = plt.figure(figsize=(10, 6))
    if hasattr(обученная_модель, 'feature_importances_'):
        важность = обученная_модель.feature_importances_
        plt.bar(range(len(важность)), важность)
        plt.title(f"Важность признаков ({настройки_визуализации})")
        plt.xlabel("Индекс признака")
        plt.ylabel("Значение")
    else:
        plt.text(0.5, 0.5, "Данные о важности признаков недоступны", ha='center')

    график_сравнения = plt.figure(figsize=(10, 6))
    plt.text(0.5, 0.5, f"График предсказаний требует внешних данных\nРесурсы: {размер_буфера}", ha='center')
    plt.title("Предсказание vs Реальность")
    
    return график_важности, график_сравнения

# [A0] Система загрузки, анализа и предсказания производственных данных на основе машинного обучения
def система_загрузки_анализа_и_предсказания_производственных_данных_на_основе_машинного_обучения_a0(путь_к_файлу, обученная_модель=None, библиотеки=None, нейросетевые_модели=None, ресурсы=None):
    import pandas as pd

    обучающая_выборка, тестовая_выборка = предобработка_данных_a1(путь_к_файлу, библиотеки, ресурсы)
    
    метрики, итоговая_модель = обучение_использование_модели_для_предсказания_производственных_данных_a2(
        обучающая_выборка, 
        тестовая_выборка, 
        обученная_модель, 
        нейросетевые_модели, 
        библиотеки, 
        ресурсы
    )
    
    график_важности, график_сравнения = создание_графиков_с_результатами_a3(итоговая_модель, библиотеки, ресурсы)
    
    return метрики, график_важности, график_сравнения, итоговая_модель

