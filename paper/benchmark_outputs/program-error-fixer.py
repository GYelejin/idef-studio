# [A33] Тестирование
def тестирование_a33(тестовая_ветка, техническое_задание, разработчик):
    import random

    try:
        код_из_ветки = тестовая_ветка.get("содержимое", "")
        статус_ветки = тестовая_ветка.get("статус", "неизвестно") if isinstance(тестовая_ветка, dict) else "ошибка"
        
        # Имитация процесса запуска тестов с учетом требований ТЗ
        результаты_тестов = random.choice(["пройдено", "провалено", "частично пройдено"])
        
        # Проверка соответствия ТЗ (имитация анализа кода на соответствие ТЗ)
        соответствует_тз = "ТЗ" in техническое_задание or техническое_задание is not None
        
        if статус_ветки == "создана" and результаты_тестов == "пройдено" and соответствует_тз:
            исправленный_код = код_из_ветки
            данные_об_ошибке = {"статус": "исправлено", "тесты": "успешно", "проверил": разработчик}
        else:
            исправленный_код = None
            данные_об_ошибке = {
                "статус": "ошибка сохраняется", 
                "тесты": результаты_тестов, 
                "замечание": "Код не прошел тестирование или не соответствует ТЗ",
                "проверил": разработчик
            }
            
    except Exception as ошибка:
        исправленный_код = None
        данные_об_ошибке = {"ошибка_тестирования": str(ошибка), "разработчик": разработчик}
        
    return исправленный_код, данные_об_ошибке

