# [A1] Создание матрицы заданного размера
def создание_матрицы_заданного_размера_a1(размер):
    from typing import List
    return [[0 for _ in range(размер)] for _ in range(размер)]

# [A2] Генерация чисел Фибоначчи в необходимом количестве
def генерация_чисел_фибоначчи_в_необходимом_количестве_a2(размер_матрицы, логика_генерации=None):
    from typing import List
    
    количество = размер_матрицы * размер_матрицы
    if логика_генерации is None:
        логика_генерации = (0, 1)
    
    а, б = логика_генерации
    последовательность = []
    
    for _ in range(количество):
        последовательность.append(а)
        а, б = б, а + б
        
    return последовательность

# [A31] Получение позиции числа Фибоначи
def получение_позиции_числа_фибоначи_a31(последовательность_чисел_фибоначчи, сигнал_о_занятости_позиции, запрос_следующего_числа, генератор_случайных_чисел):
    import random
    from typing import Tuple

    размер = int(len(последовательность_чисел_фибоначчи)**0.5)
    
    if hasattr(генератор_случайных_чисел, 'randint'):
        функция_рандома = генератор_случайных_чисел.randint
    else:
        функция_рандома = random.randint

    if not запрос_следующего_числа:
        return (0, 0)

    строка = функция_рандома(0, размер - 1)
    столбец = функция_рандома(0, размер - 1)
    
    if сигнал_о_занятости_позиции:
        строка = (строка + 1) % размер
        столбец = (столбец + 1) % размер
        
    return (строка, столбец)

# [A32] Проверка занята ли позиция другим
def проверка_занята_ли_позиция_другим_a32(матрица, сгенерированная_позиция):
    from typing import Tuple, Any
    
    строка, столбец = сгенерированная_позиция
    значение_в_ячейке = матрица[строка][столбец]
    
    занято = значение_в_ячейке != 0
    
    return (значение_в_ячейке, сгенерированная_позиция), занято

# [A33] Поставить число на место
def поставить_число_на_место_a33(получение_числа_и_позиции):
    from typing import Tuple, Any
    
    # Согласно спецификации, на вход подается только 'получение_числа_и_позиции'.
    # Чтобы функция была работоспособной и возвращала матрицу, 
    # предполагается, что объект 'получение_числа_и_позиции' является кортежем, 
    # содержащим (значение, позиция, матрица, число_для_вставки).
    
    значение, позиция, матрица, число_для_вставки = получение_числа_и_позиции
    строка, столбец = позиция
    
    новая_матрица = [строка_м[:] for строка_м in матрица]
    новая_матрица[строка][столбец] = число_для_вставки
    
    запрос_следующего_числа = True
    
    return запрос_следующего_числа, новая_матрица

# [A3] Заполнение Матрицы числами Фибоначчи в случайном порядке
def заполнение_матрицы_числами_фибоначчи_в_случайном_порядке_a3(пустая_матрица, последовательность_чисел_фибоначчи, генератор_случайных_чисел):
    from typing import List
    
    текущая_матрица = пустая_матрица
    запрос_следующего_числа = True
    сигнал_о_занятости_позиции = False
    
    for число in последовательность_чисел_фибоначчи:
        while True:
            позиция = получение_позиции_числа_фибоначи_a31(
                последовательность_чисел_фибоначчи, 
                сигнал_о_занятости_позиции, 
                запрос_следующего_числа, 
                генератор_случайных_чисел
            )
            
            данные_позиции, сигнал_о_занятости_позиции = проверка_занята_ли_позиция_другим_a32(
                текущая_матрица, 
                позиция
            )
            
            if not сигнал_о_занятости_позиции:
                # Подготовка данных для функции a33 согласно её реализации: (значение, позиция, матрица, число_для_вставки)
                вход_для_a33 = (данные_позиции[0], данные_позиции[1], текущая_матрица, число)
                запрос_следующего_числа, текущая_матрица = поставить_число_на_место_a33(вход_для_a33)
                break
                
    return текущая_матрица

# [A0] Заполнение случайным образом матрицы последовательными без повторений числами Фибоначчи
def заполнение_случайным_образом_матрицы_последовательными_без_повторений_числами_фибоначчи_a0(размер_матрицы, логика_генерации, генератор_случайных_чисел):
    from typing import List
    
    пустая_матрица = создание_матрицы_заданного_размера_a1(размер_матрицы)
    
    последовательность_фибоначчи = генерация_чисел_фибоначчи_в_необходимом_количестве_a2(
        размер_матрицы, 
        логика_генерации
    )
    
    результат_матрица = заполнение_матрицы_числами_фибоначчи_в_случайном_порядке_a3(
        пустая_матрица, 
        последовательность_фибоначчи, 
        генератор_случайных_чисел
    )
    
    return результат_матрица

# ==============================================================================
# Точка входа и ввод данных
# ==============================================================================

def main() -> None:
    import random
    print("=== Запуск: Матрица Фибоначчи ===")

    # Подготовка входных данных конвейера:
    размер_матрицы = int(input("Введите размерность матрицы (N x N) [Enter: 3]: ") or "3")
    логика_генерации = (0, 1)  # Базовая логика генерации (начальные члены F0=0, F1=1)
    генератор_случайных_чисел = random.Random(int(input("Введите seed генератора случайных чисел [Enter: 42]: ") or "42"))

    try:
        результат = заполнение_случайным_образом_матрицы_последовательными_без_повторений_числами_фибоначчи_a0(размер_матрицы=размер_матрицы, логика_генерации=логика_генерации, генератор_случайных_чисел=генератор_случайных_чисел)
        print("Выполнение завершено успешно:")
        if isinstance(результат, list):
            for строка in результат:
                print(" ", строка)
        else:
            print(результат)
    except Exception as e:
        print(f"Ошибка при выполнении конвейера: {e}")


if __name__ == "__main__":
    main()
