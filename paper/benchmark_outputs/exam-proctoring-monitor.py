# ==============================================================================

def main() -> None:
    import random
    print("=== Запуск: Контроль поведения студентов во время экзаменов ===")

    # Подготовка входных данных конвейера:
    видео_с_камер_в_аудитории = input("Введите значение для видео_с_камер_в_аудитории: ")
    правила_проведения_экзамена = (0, 1)  # Базовая логика генерации (начальные члены F0=0, F1=1)
    модели_компьютерного_зрения_для_анализа_поведения = input("Введите значение для модели_компьютерного_зрения_для_анализа_поведения: ")

    try:
        результат = контроль_поведения_студентов_во_время_экзаменов_a0(видео_с_камер_в_аудитории=видео_с_камер_в_аудитории, правила_проведения_экзамена=правила_проведения_экзамена, модели_компьютерного_зрения_для_анализа_поведения=модели_компьютерного_зрения_для_анализа_поведения)
        print("Выполнение завершено успешно:")
        if isinstance(результат, list):
            for строка in результат:
                print(" ", строка)
        else:
            print(результат)
    except Exception as e:
        print(f"Ошибка при выполнении конвейера: {e}")


if __name__ == "__main__":
    main()
