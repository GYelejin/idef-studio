# [A1] Захват видео.
def захват_видео_a1(видео_с_камер_в_аудитории):
    import cv2
    import numpy as np
    
    кадры_видео = []
    
    if isinstance(видео_с_камер_в_аудитории, int):
        захват = cv2.VideoCapture(видео_с_камер_в_аудитории)
        while True:
            успех, кадр = захват.read()
            if not успех:
                break
            кадры_видео.append(кадр)
        захват.release()
    elif isinstance(видео_с_камер_в_аудитории, str):
        захват = cv2.VideoCapture(видео_с_камер_в_аудитории)
        while True:
            успех, кадр = захват.read()
            if not успех:
                break
            кадры_видео.append(кадр)
        захват.release()
    elif isinstance(видео_с_камер_в_аудитории, list):
        кадры_видео = видео_с_камер_в_аудитории
    else:
        кадры_видео = []
        
    return кадры_видео

# [A2] Анализ движений (взгляды, жесты).
def анализ_движений_взгляды_жесты_a2(кадры_видео, модели_компьютерного_зрения_для_анализа_поведения=None):
    import numpy as np
    from typing import List, Dict, Any

    если_модели_отсутствуют = модели_компьютерного_зрения_для_анализа_поведения is None
    результаты_анализа = []

    for индекс_кадра, кадр in enumerate(кадры_видео):
        if если_модели_отсутствуют:
            информация_о_движениях = {
                "номер_кадра": индекс_кадра,
                "взгляд": "не определен",
                "жесты": "не определены",
                "уверенность": 0.0
            }
        else:
            модель = модели_компьютерного_зрения_для_анализа_поведения
            try:
                анализ = модель.predict(кадр)
                информация_о_движениях = {
                    "номер_кадра": индекс_кадра,
                    "взгляд": анализ.get("gaze", "неизвестно"),
                    "жесты": анализ.get("gestures", "неизвестно"),
                    "уверенность": анализ.get("confidence", 0.0)
                }
            except Exception:
                информация_о_движениях = {
                    "номер_кадра": индекс_кадра,
                    "взгляд": "ошибка анализа",
                    "жесты": "ошибка анализа",
                    "уверенность": 0.0
                }
        результаты_анализа.append(информация_о_движениях)

    return результаты_анализа

# [A3] Обнаружение подозрительных действий.
def обнаружение_подозрительных_действий_a3(классифицированная_информация_о_текущих_движениях_студентов, правила_проведения_экзамена=None):
    from typing import List, Dict, Any

    если_правила_не_заданы = правила_проведения_экзамена is None
    список_нарушений = []
    
    правила_по_умолчанию = {
        "запрещенные_взгляды": ["влево", "вправо", "на соседа"],
        "запрещенные_жесты": ["передача записки", "использование телефона", "шепот"],
        "порог_уверенности": 0.7
    }
    
    актуальные_правила = правила_по_умолчанию if если_правила_не_заданы else правила_проведения_экзамена

    for запись in классифицированная_информация_о_текущих_движениях_студентов:
        взгляд = запись.get("взгляд")
        жесты = запись.get("жесты")
        уверенность = запись.get("уверенность", 0.0)
        
        подозрение = False
        причина = ""
        
        if уверенность >= актуальные_правила.get("порог_уверенности", 0.7):
            if взгляд in актуальные_правила.get("запрещенные_взгляды", []):
                подозрение = True
                причина = f"Подозрительный взгляд: {взгляд}"
            elif жесты in актуальные_правила.get("запрещенные_жесты", []):
                подозрение = True
                причина = f"Подозрительный жест: {жесты}"
        
        if подозрение:
            список_нарушений.append({
                "номер_кадра": запись.get("номер_кадра"),
                "тип_нарушения": причина,
                "уверенность": уверенность
            })
            
    return список_нарушений

# [A4] Уведомление о нарушениях.
def уведомление_о_нарушениях_a4(информация_о_подозрительных_действиях):
    from datetime import datetime
    from typing import List, Dict, Any

    список_уведомлений = []
    текущее_время = datetime.now().strftime("%Y-%m-%d %H:%M:%S")

    if not информация_о_подозрительных_действиях:
        return "Нарушений не обнаружено"

    for нарушение in информация_о_подозрительных_действиях:
        номер_кадра = нарушение.get("номер_кадра", "неизвестен")
        тип_нарушения = нарушение.get("тип_нарушения", "неопределенное действие")
        уверенность = нарушение.get("уверенность", 0.0)
        
        текст_уведомления = (
            f"[{текущее_время}] ВНИМАНИЕ: Обнаружено нарушение! "
            f"Кадр: {номер_кадра}, Тип: {тип_нарушения}, "
            f"Достоверность: {уверенность:.2%}"
        )
        список_уведомлений.append(текст_уведомления)

    return список_уведомлений

# [A0] Контроль поведения студентов во время экзаменов
def контроль_поведения_студентов_во_время_экзаменов_a0(видео_с_камер_в_аудитории, правила_проведения_экзамена, модели_компьютерного_зрения_для_анализа_поведения):
    from typing import Any

    кадры = захват_видео_a1(видео_с_камер_в_аудитории)
    анализ_движений = анализ_движений_взгляды_жесты_a2(кадры, модели_компьютерного_зрения_для_анализа_поведения)
    нарушения = обнаружение_подозрительных_действий_a3(анализ_движений, правила_проведения_экзамена)
    уведомления = уведомление_о_нарушениях_a4(нарушения)
    
    return уведомления

# ==============================================================================
