"""
Заполнить случайным образом матрицу последовательными без повторений числами Фибоначчи.
Сгенерировано автоматически в едином диалоговом контексте.
Стиль: чистые функции, внутренние импорты.
"""

from __future__ import annotations

# ==============================================================================
# Функции
# ==============================================================================

# [A11] Проверить N > 0 M >0
def проверить_0_0_a11(n, m):
    if n <= 0 or m <= 0:
        raise ValueError("Ошибка: Неположительные числа")
    return n, m

# [A12] Проверить что: N <= N_MAX M <= M_MAX
def проверить_что_a12(n, m, n_max, m_max):
    if n > n_max or m > m_max:
        raise ValueError("Ошибка: Слишком большие числа")
    return n, m

# [A13] Создать матрицу размером NxM
def создать_матрицу_размером_a13(n, m):
    return [[0 for _ in range(m)] for _ in range(n)]

# [A1] Создать матрицу размером NxM
def создать_матрицу_размером_a1(n, m, n_max, m_max):
    n_val, m_val = проверить_0_0_a11(n, m)
    n_val, m_val = проверить_что_a12(n_val, m_val, n_max, m_max)
    return создать_матрицу_размером_a13(n_val, m_val)

# [A21] Создать массив
def создать_массив_a21(m_max, n_max):
    return [0] * (n_max * m_max)

# [A22] Проверить N > 0 M >0
def проверить_0_0_a22(n, m):
    if n <= 0 or m <= 0:
        return f"Ошибка: Неположительные числа, {n} и {m}"
    return n, m

# [A23] Проверить что: N <= N_MAX M <= M_MAX
def проверить_что_a23(n, m, m_max, n_max):
    if n > n_max or m > m_max:
        return f"Ошибка: Слишком большие числа, {n} и {m}"
    return n, m

# [A24] Заполнить массив NxM последовательными эллементами
def заполнить_массив_последовательными_эллементами_a24(n, m, массив):
    счетчик = 1
    for i in range(n):
        for j in range(m):
            массив[i * m + j] = счетчик
            счетчик += 1
    return массив[:n * m]

# [A2] Создать массив последовательных чисел от 1 до NxM
def создать_массив_последовательных_чисел_от_1_до_a2(n, m, n_max, m_max):
    результат_проверки_1 = проверить_0_0_a22(n, m)
    if isinstance(результат_проверки_1, str):
        return результат_проверки_1
    
    n_val, m_val = результат_проверки_1
    результат_проверки_2 = проверить_что_a23(n_val, m_val, m_max, n_max)
    if isinstance(результат_проверки_2, str):
        return результат_проверки_2
    
    n_val, m_val = результат_проверки_2
    массив_базовый = создать_массив_a21(m_val, n_val)
    return заполнить_массив_последовательными_эллементами_a24(n_val, m_val, массив_базовый)

# [A311] Получение случайного числа методом rand()
def получение_случайного_числа_методом_a311(запрос):
    import random
    return random.random()

# [A312] Преобразование случайного числа (число % len_mass)
def преобразование_случайного_числа_число_a312(случайное_число, len_mass=1):
    return int(случайное_число) % len_mass

# [A313] Получение числа хранящегося по индексу k, сокращение len_mass на 1, удаление k-го эллемента, Возвращение числа хранящегося по индексу k (число i)
def получение_числа_хранящегося_по_индексу_сокращение_на_1_удаление_го_эллемента_возвращение_числа_хранящегося_по_индексу_число_a313(массив_последовательных_чисел, k):
    число_i = массив_последовательных_чисел.pop(k)
    return число_i

# [A31] Получение случайного числа от 1 до NxM
def получение_случайного_числа_от_1_до_a31(массив_последовательных_чисел, запрос):
    случайное_число_raw = получение_случайного_числа_методом_a311(запрос)
    k = преобразование_случайного_числа_число_a312(случайное_число_raw, len(массив_последовательных_чисел))
    return получение_числа_хранящегося_по_индексу_сокращение_на_1_удаление_го_эллемента_возвращение_числа_хранящегося_по_индексу_число_a313(массив_последовательных_чисел, k)

# [A32] Получение i-го числа фибоначи
def получение_го_числа_фибоначи_a32(i, фибо_1=1, фибо_2=2):
    if i <= 0:
        return 0
    if i == 1:
        return фибо_1
    if i == 2:
        return фибо_2
    
    а, б = фибо_1, фибо_2
    for _ in range(3, i + 1):
        а, б = б, а + б
    return б

# [A33] Проход по всем эллементам матрицы и заполнение новых эллементов
def проход_по_всем_эллементам_матрицы_и_заполнение_новых_эллементов_a33(матрица, n, m, число_фибоначчи):
    запрос = True
    for r in range(n):
        for c in range(m):
            if матрица[r][c] == 0:
                матрица[r][c] = число_фибоначчи
                return матрица, запрос
    return матрица, False

# [A3] Заполнить матрицу числами Фибоначчи случайным образом
def заполнить_матрицу_числами_фибоначчи_случайным_образом_a3(матрица, массив_последовательных_чисел, n, m):
    текущая_матрица = матрица
    текущий_массив = list(массив_последовательных_чисел)
    запрос = True
    
    while запрос:
        i = получение_случайного_числа_от_1_до_a31(текущий_массив, запрос)
        число_фибо = получение_го_числа_фибоначи_a32(i)
        текущая_матрица, запрос = проход_по_всем_эллементам_матрицы_и_заполнение_новых_эллементов_a33(текущая_матрица, n, m, число_фибо)
        
    return текущая_матрица

# [A0] Заполнить случайным образом матрицу последовательными без повторений числами Фибоначчи.
def заполнить_случайным_образом_матрицу_последовательными_без_повторений_числами_фибоначчи_a0(n, m):
    n_max, m_max = 100, 100
    матрица = создать_матрицу_размером_a1(n, m, n_max, m_max)
    массив_чисел = создать_массив_последовательных_чисел_от_1_до_a2(n, m, n_max, m_max)
    
    if isinstance(матрица, str) or isinstance(массив_чисел, str):
        return матрица if isinstance(матрица, str) else массив_чисел
        
    return заполнить_матрицу_числами_фибоначчи_случайным_образом_a3(матрица, массив_чисел, n, m)

# ==============================================================================
# Точка входа и ввод данных
# ==============================================================================

def main() -> None:
    import random
    print("=== Запуск: Заполнить случайным образом матрицу последовательными без повторений числами Фибоначчи. ===")

    # Подготовка входных данных конвейера:
    n = input("Введите значение для n: ")
    m = input("Введите значение для m: ")

    try:
        результат = заполнить_случайным_образом_матрицу_последовательными_без_повторений_числами_фибоначчи_a0(n=n, m=m)
        print("Выполнение завершено успешно:")
        if isinstance(результат, list):
            for строка in результат:
                print(" ", строка)
        else:
            print(результат)
    except Exception as e:
        print(f"Ошибка при выполнении конвейера: {e}")


if __name__ == "__main__":
    main()
