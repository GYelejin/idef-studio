# [A1] Анализ видеоуроков (вовлеченность).
def анализ_видеоуроков_вовлеченность_a1(видео_занятий, данные_о_работе_студентов):
    from typing import List, Dict, Any

    результаты_анализа = []
    список_всех_видео = [видео.get('id') for видео in видео_занятий]
    общее_количество_видео = len(список_всех_видео)

    for студент in данные_о_работе_студентов:
        идентификатор_студента = студент.get('id')
        просмотренные_видео = студент.get('просмотренные_видео', [])
        
        количество_просмотренных = len(просмотренные_видео)
        процент_покрытия_курса = (количество_просмотренных / общее_количество_видео * 100) if общее_количество_видео > 0 else 0
        
        сумма_процентов_просмотра = sum(видео.get('процент_просмотра', 0) for видео in просмотренные_видео)
        средний_процент_просмотра = (сумма_процентов_просмотра / количество_просмотренных) if количество_просмотренных > 0 else 0
        
        активность_в_тестах = студент.get('активность_в_тестах', 0)
        
        общая_вовлеченность = (средний_процент_просмотра * 0.5) + (процент_покрытия_курса * 0.3) + (активность_в_тестах * 0.2)
        
        результаты_анализа.append({
            'id_студента': идентификатор_студента,
            'уровень_вовлеченности': общая_вовлеченность,
            'просмотрено_уроков': количество_просмотренных,
            'процент_покрытия': процент_покрытия_курса
        })
        
    return результаты_анализа

# [A2] Сравнение с прогрессом.
def сравнение_с_прогрессом_a2(проанализированная_информация, правила_анализа_прогресса_студентов, компьютерное_зрение_для_анализа_вовлеченности):
    from typing import List, Dict, Any

    результаты_сравнения = []
    
    порог_низкой_вовлеченности = правила_анализа_прогресса_студентов.get('порог_низкой_вовлеченности', 40.0)
    порог_высокой_вовлеченности = правила_анализа_прогресса_студентов.get('порог_высокой_вовлеченности', 80.0)

    for запись in проанализированная_информация:
        уровень_вовлеченности = запись.get('уровень_вовлеченности', 0.0)
        
        данные_кв = компьютерное_зрение_для_анализа_вовлеченности.get(запись.get('id_студента'), {})
        коэффициент_внимания = данные_кв.get('коэффициент_внимания', 1.0)
        
        скорректированная_вовлеченность = уровень_вовлеченности * коэффициент_внимания
        
        if скорректированная_вовлеченность < порог_низкой_вовлеченности:
            статус_прогресса = 'отстает'
        elif скорректированная_вовлеченность > порог_высокой_вовлеченности:
            статус_прогресса = 'опережает'
        else:
            статус_прогресса = 'в норме'
            
        результаты_сравнения.append({
            'id_студента': запись.get('id_студента'),
            'итоговая_вовлеченность': скорректированная_вовлеченность,
            'статус_прогресса': статус_прогресса,
            'процент_покрытия': запись.get('процент_покрытия', 0)
        })
        
    return результаты_сравнения

# [A3] Генерация рекомендаций.
def генерация_рекомендаций_a3(проанализированная_информация_сравненная_с_прогрессом, машинное_обучение_для_рекомендаций):
    from typing import List, Dict, Any

    сгенерированные_рекомендации = []
    
    база_контента = машинное_обучение_для_рекомендаций.get('база_контента', {
        'дополнительные_материалы': ['Гайд по основам', 'Практический воркшоп', 'Список литературы'],
        'углубленные_курсы': ['Продвинутый модуль А', 'Специализация Б', 'Мастер-класс В']
    })

    for запись in проанализированная_информация_сравненная_с_прогрессом:
        идентификатор_студента = запись.get('id_студента')
        статус = запись.get('статус_прогресса')
        вовлеченность = запись.get('итоговая_вовлеченность', 0.0)
        
        рекомендации_для_студента = []
        
        if статус == 'отстает' or вовлеченность < 50.0:
            рекомендации_для_студента.append('Рекомендуется пересмотреть базовые модули')
            рекомендации_для_студента.extend(база_контента['дополнительные_материалы'][:2])
        elif статус == 'опережает':
            рекомендации_для_студента.append('Вы демонстрируете отличные успехи!')
            рекомендации_для_студента.extend(база_контента['углубленные_курсы'])
        else:
            рекомендации_для_студента.append('Продолжайте двигаться в текущем темпе')
            рекомендации_для_студента.append(база_контента['дополнительные_материалы'][0])
            
        сгенерированные_рекомендации.append({
            'id_студента': идентификатор_студента,
            'список_рекомендаций': рекомендации_для_студента,
            'приоритет': 'высокий' if статус == 'отстает' else 'средний'
        })
        
    return сгенерированные_рекомендации

# [A4] Представление рекомендаций через интерфейс.
def представление_рекомендаций_через_интерфейс_a4(сгенерированные_рекомендации):
    from typing import List, Dict, Any

    итоговый_интерфейс = []
    
    for запись in сгенерированные_рекомендации:
        идентификатор = запись.get('id_студента')
        список = запись.get('список_рекомендаций', [])
        приоритет = запись.get('приоритет', 'обычный')
        
        текст_рекомендаций = "\n".join([f"- {пункт}" for пункт in список])
        
        оформленный_блок = (
            f"Студент ID: {идентификатор}\n"
            f"Приоритет внимания: {приоритет.upper()}\n"
            f"Рекомендации для улучшения навыков:\n{текст_рекомендаций}"
        )
        
        итоговый_интерфейс.append({
            'id_студента': идентификатор,
            'визуальный_блок': оформленный_блок
        })
        
    return итоговый_интерфейс

# [A0] Персонализированные рекомендации по обучению
def персонализированные_рекомендации_по_обучению_a0(видео_занятий_и_данные_студентов, правила_анализа_прогресса, компьютерное_зрение, машинное_обучение):
    from typing import List, Dict, Any

    # Распаковка входных данных, если они переданы как кортеж или список
    видео_занятий = видео_занятий_и_данные_студентов[0] if isinstance(видео_занятий_и_данные_студентов, (list, tuple)) else None
    данные_о_работе_студентов = видео_занятий_и_данные_студентов[1] if isinstance(видео_занятий_и_данные_студентов, (list, tuple)) else видео_занятий_и_данные_студентов

    # Шаг 1: Анализ вовлеченности
    проанализированная_информация = анализ_видеоуроков_вовлеченность_a1(
        видео_занятий, 
        данные_о_работе_студентов
    )

    # Шаг 2: Сравнение с прогрессом
    сравненная_информация = сравнение_с_прогрессом_a2(
        проанализированная_информация, 
        правила_анализа_прогресса, 
        компьютерное_зрение
    )

    # Шаг 3: Генерация рекомендаций
    сгенерированные_рекомендации = генерация_рекомендаций_a3(
        сравненная_информация, 
        машинное_обучение
    )

    # Шаг 4: Представление через интерфейс
    итоговые_рекомендации = представление_рекомендаций_через_интерфейс_a4(
        сгенерированные_рекомендации
    )

    return итоговые_рекомендации

