# [A1] Составление списка всевозможных комбинаций 2-х точек
def составление_списка_всевозможных_комбинаций_2_х_точек_a1():
    from itertools import combinations
    from random import random
    # Поскольку входные параметры отсутствуют, генерируем набор случайных точек для обеспечения работоспособности
    список_точек = [(random(), random()) for _ in range(10)]
    return list(combinations(список_точек, 2))

# [A21] провести прямую через 2 точки
def провести_прямую_через_2_точки_a21():
    from random import random
    точка1 = (random(), random())
    точка2 = (random(), random())
    x1, y1 = точка1
    x2, y2 = точка2
    a = y2 - y1
    b = x1 - x2
    c = x2 * y1 - y2 * x1
    return None

# [A22] Посчитать кол-во точек слева
def посчитать_кол_во_точек_слева_a22():
    from random import random
    список_точек = [(random(), random()) for _ in range(10)]
    параметры_прямой = (random(), random(), random())
    a, b, c = параметры_прямой
    количество_слева = 0
    for x, y in список_точек:
        if a * x + b * y + c > 0:
            количество_слева += 1
    return количество_слева

# [A23] Посчитать кол-во точек справа
