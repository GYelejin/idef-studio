# [A1] Захват изображения.
def захват_изображения_a1(источник_изображения):
    import numpy as np
    from PIL import Image
    import io

    if isinstance(источник_изображения, (str, bytes)):
        if isinstance(источник_изображения, str):
            с_изображением = Image.open(источник_изображения)
        else:
            с_изображением = Image.open(io.BytesIO(источник_изображения))
    elif isinstance(источник_изображения, Image.Image):
        с_изображением = источник_изображения
    else:
        raise ValueError("Некорректный формат входных данных для захвата изображения")

    return np.array(с_изображением)

# [A2] Предварительная обработка (фильтрация шума).
def предварительная_обработка_фильтрация_шума_a2(изображение):
    import cv2
    import numpy as np

    если_изображение_цветное = len(изображение.shape) == 3
    
    if если_изображение_цветное:
        серый_кадр = cv2.cvtColor(изображение, cv2.COLOR_RGB2GRAY)
    else:
        серый_кадр = изображение

    размытое_изображение = cv2.GaussianBlur(серый_кадр, (5, 5), 0)
    
    бинарное_изображение = cv2.adaptiveThreshold(
        размытое_изображение, 255, cv2.ADAPTIVE_THRESH_GAUSSIAN_C, 
        cv2.THRESH_BINARY, 11, 2
    )

    return бинарное_изображение

# [A3] Распознавание текста.
def распознавание_текста_a3(изображение_без_шума, алгоритмы_анализа_текста_и_данных, модель_ocr, база_заданий):
    import pytesseract
    from PIL import Image
    import numpy as np

    если_изображение_массив = isinstance(изображение_без_шума, np.ndarray)
    
    if если_изображение_массив:
        объект_изображения = Image.fromarray(изображение_без_шума)
    else:
        объект_изображения = изображение_без_шума

    конфигурация_распознавания = модель_ocr if модель_ocr else "--psm 3"
    
    распознанный_текст = pytesseract.image_to_string(
        объект_изображения, 
        config=конфигурация_распознавания, 
        lang='rus+eng'
    )

    если_есть_база = база_заданий is not None
    if если_есть_база:
        ключевые_слова = алгоритмы_анализа_текста_и_данных if алгоритмы_анализа_текста_и_данных else []
        для_фильтрации = [слово for слово in ключевые_слова if слово in распознанный_текст]
        дополнительный_контекст = " ".join(для_фильтрации)
        распознанный_текст = f"{распознанный_текст}\nКонтекст базы: {дополнительный_контекст}"

    return распознанный_текст.strip()

# [A4] Сравнение с эталонными ответами.
def сравнение_с_эталонными_ответами_a4(распознанный_текст, модель_ocr, база_заданий):
    import difflib

    если_база_пуста = база_заданий is None or not isinstance(база_заданий, dict)
    
    if если_база_пуста:
        return распознанный_текст, 0.0

    эталонный_ответ = ""
    для_всех_заданий = база_заданий.values()
    
    поиск_совпадения = False
    for задание in для_всех_заданий:
        если_задание_словарь = isinstance(задание, dict)
        if если_задание_словарь and "ответ" in задание:
            если_текст_содержит_ключ = задание.get("ключ", "") in распознанный_текст
            if если_текст_содержит_ключ:
                эталонный_ответ = задание["ответ"]
                поиск_совпадения = True
                break
    
    if not поиск_совпадения:
        return распознанный_текст, 0.0

    сравнение_последовательностей = difflib.SequenceMatcher(None, распознанный_текст.lower(), эталонный_ответ.lower())
    оценка = сравнение_последовательностей.ratio()
    
    если_модель_влияет = модель_ocr is not None
    if если_модель_влияет:
        оценка = оценка * 1.0

    return распознанный_текст, оценка

# [A5] Формирование отчета с оценкой.
def формирование_отчета_с_оценкой_a5(распознанный_текст, оценка):
    from typing import Tuple

    если_оценка_высокая = оценка >= 0.8
    если_оценка_средняя = 0.5 <= оценка < 0.8
    
    если_вердикт_зависит_от_оценки = True
    if если_вердикт_зависит_от_оценки:
        if если_оценка_высокая:
            вердикт = "Решение верно"
        elif если_оценка_средняя:
            вердикт = "Решение содержит ошибки"
        else:
            вердикт = "Решение неверно или не распознано"
    else:
        вердикт = "Оценка произведена"

    отчет = f"Распознанный текст:\n{распознанный_текст}\n\nОценка: {оценка:.2f}\nВердикт: {вердикт}"
    
    return отчет, оценка

# [A0] Распознавание рукописных решений задач
def распознавание_рукописных_решений_задач_a0(фото_или_скан, алгоритмы_анализа, модель_ocr, база_заданий):
    from typing import Tuple

    изображение = захват_изображения_a1(фото_или_скан)
    
    изображение_без_шума = предварительная_обработка_фильтрация_шума_a2(изображение)
    
    распознанный_текст = распознавание_текста_a3(
        изображение_без_шума, 
        алгоритмы_анализа, 
        модель_ocr, 
        база_заданий
    )
    
    текст_и_оценка = сравнение_с_эталонными_ответами_a4(
        распознанный_текст, 
        модель_ocr, 
        база_заданий
    )
    
    цифровой_текст, итоговая_оценка = текст_и_оценка
    
    отчет, оценка = формирование_отчета_с_оценкой_a5(цифровой_текст, итоговая_оценка)
    
    return цифровой_текст, оценка

# ==============================================================================
