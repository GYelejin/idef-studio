def main() -> None:
    import random
    print("=== Запуск: Заполнение случайным образом матрицы последовательными без повторений числами Фибоначчи ===")

    # Подготовка входных данных конвейера:
    размер = int(input("Введите размерность матрицы (N x N) [Enter: 3]: ") or "3")
    логика_генерации = (0, 1)  # Базовая логика генерации (начальные члены F0=0, F1=1)
    генератор_случайных_чисел = random.Random(int(input("Введите seed генератора случайных чисел [Enter: 42]: ") or "42"))

    try:
        результат = заполнение_случайным_образом_матрицы_последовательными_без_повторений_числами_фибоначчи_a0(размер=размер, логика_генерации=логика_генерации, генератор_случайных_чисел=генератор_случайных_чисел)
        print("Выполнение завершено успешно:")
        if isinstance(результат, list):
            for строка in результат:
                print(" ", строка)
        else:
            print(результат)
    except Exception as e:
        print(f"Ошибка при выполнении конвейера: {e}")


if __name__ == "__main__":
    main()
