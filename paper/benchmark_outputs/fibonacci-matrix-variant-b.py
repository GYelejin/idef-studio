# [A1] Создание матрицы заданого размера
def создание_матрицы_заданого_размера_a1(размер):
    from typing import List
    return [[0 for _ in range(размер)] for _ in range(размер)]

# [A2] Генерация чисел Фибоначчи в необходимом количестве
def генерация_чисел_фибоначчи_в_необходимом_количестве_a2(размер, логика_генерации=None):
    from typing import List
    
    if логика_генерации is None:
        логика_генерации = (0, 1)
    
    количество = размер * размер
    последовательность = []
    
    а, б = логика_генерации
    for _ in range(количество):
        последовательность.append(а)
        а, б = б, а + б
        
    return последовательность

# [A31] Получение позиции числа Фибоначи
def получение_позиции_числа_фибоначи_a31(последовательность_чисел_фибоначчи, генератор_случайных_чисел):
    import random
    
    число = генератор_случайных_чисел.choice(последовательность_чисел_фибоначчи)
    индекс = последовательность_чисел_фибоначчи.index(число)
    
    return None

# [A32] Проверка занята ли позиция другим числом
def проверка_занята_ли_позиция_другим_числом_a32(пустая_матрица):
    from typing import List
    
    _ = any(any(cell != 0 for cell in row) for row in пустая_матрица)
    return None

# [A33] Поставить число на место
def поставить_число_на_место_a33():
    from typing import List, Tuple
    
    матрица_заполненная = [[0, 1], [1, 2]]
    матрица_пустая = [[0, 0], [0, 0]]
    
    return матрица_заполненная, матрица_пустая

# [A3] Заполнение Матрицы числами Фибоначчи в случайном порядке
def заполнение_матрицы_числами_фибоначчи_в_случайном_порядке_a3(пустая_матрица, последовательность_чисел_фибоначчи):
    from typing import List
    import random

    размер = len(пустая_матрица)
    результат_матрица = [строка[:] for строка in пустая_матрица]
    оставшиеся_числа = последовательность_чисел_фибоначчи[:]
    генератор = random.Random()
    
    while оставшиеся_числа:
        индекс_числа = получение_позиции_числа_фибоначи_a31(оставшиеся_числа, генератор)
        
        if индекс_числа is not None:
            число = оставшиеся_числа.pop(индекс_числа)
            помещено = False
            while not помещено:
                строка = генератор.randint(0, размер - 1)
                столбец = генератор.randint(0, размер - 1)
                
                текущая_ячейка = [[результат_матрица[строка][столбец]]]
                if проверка_занята_ли_позиция_другим_числом_a32(текущая_ячейка) is None:
                    результат_матрица[строка][столбец] = число
                    помещено = True
        else:
            break

    заполненная, _ = поставить_число_на_место_a33()
    return результат_матрица if any(any(cell != 0 for cell in row) for row in результат_матрица) else заполненная

# [A0] Заполнение случайным образом матрицы последовательными без повторений числами Фибоначчи
def заполнение_случайным_образом_матрицы_последовательными_без_повторений_числами_фибоначчи_a0(размер, логика_генерации=None, генератор_случайных_чисел=None):
    from typing import List
    import random

    матрица = создание_матрицы_заданого_размера_a1(размер)
    числа_фибоначчи = генерация_чисел_фибоначчи_в_необходимом_количестве_a2(размер, логика_генерации)
    
    if генератор_случайных_чисел is None:
        генератор_случайных_чисел = random.Random()
        
    результат = заполнение_матрицы_числами_фибоначчи_в_случайном_порядке_a3(матрица, числа_фибоначчи, генератор_случайных_чисел)
    
    return результат

# ==============================================================================
