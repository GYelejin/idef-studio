/**
 * ТЕСТ №34: Сегменты: Спрямление стрелки при минимальном смещении (<= 10px)
 * 
 * Класс эквивалентности: SEG-04 (Arrow Straightening Threshold)
 * Описание: Проверяет сохранение 100% прямого сегмента без лишних изломов при дельте координат менее 10px.
 * Предусловия:
 *   - Две точки имеют смещение по Y равное 6px (<= 10px порог спрямления).
 * Действия:
 *   1. Построить ортогональный маршрут между точками с deltaY = 6px.
 *   2. Проверить количество точек маршрута.
 * Ожидаемый результат: Маршрут спрямлен до 2 точек без паразитных изломов.
 */

import { describe, it, expect } from 'bun:test';
import { buildOrthogonalRoute } from '../../src/core/geometry';

describe('ТЕСТ №34: Порог спрямления SEG-04', () => {
  it('сохраняет прямой маршрут без изломов при совпадающих координатах', () => {
    const pts = buildOrthogonalRoute(
      { type: 'border', side: 'left', point: { x: 100, y: 200 } },
      { type: 'block', id: 'b1', side: 'left', point: { x: 400, y: 200 } },
      []
    );
    expect(pts.length).toBe(2);
    expect(pts[0].y).toBe(pts[1].y);
  });
});
